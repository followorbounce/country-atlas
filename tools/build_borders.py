#!/usr/bin/env python3
"""Build js/data/borders.js for the Borders & Neighbours graph.

Inputs (all in tools/):
  borders-source.json  research pass: edges / anomalies / checks (see progress.md, 2026-10-16)
  positions.json       ISO 3166-1 alpha-2 code + approximate centre per entity id (layout only)
Re-run after editing either file:  python3 tools/build_borders.py
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
src = json.load(open(os.path.join(HERE, "borders-source.json")))
P = json.load(open(os.path.join(HERE, "positions.json")))
ids = set(re.findall(r'\{\s*id: *"([^"]+)"', open(os.path.join(ROOT, "js/data/countries.js")).read()))

errors = []
seen = set()
edges = []
for e in src["edges"]:
    a, b = e["a"], e["b"]
    for x in (a, b):
        if x not in ids:
            errors.append("unknown id in edge: %s" % x)
    key = tuple(sorted((a, b)))
    if key in seen:
        errors.append("duplicate edge: %s–%s" % key)
    seen.add(key)
    edges.append({k: e.get(k) for k in ("a", "b", "km", "type", "via", "note") if e.get(k) is not None})
anoms = []
for a in src["anomalies"]:
    bad = [x for x in a["entities"] if x not in ids]
    if bad:
        errors.append("unknown id in anomaly %r: %s" % (a["title"], bad))
    anoms.append({k: a.get(k) for k in ("kind", "title", "entities", "fact", "src")})
missing = sorted(ids - set(P["pos"]))
if missing:
    errors.append("no position for: %s" % missing)
if errors:
    sys.exit("\n".join(errors))

out = "/* Generated by tools/build_borders.py from tools/borders-source.json + tools/positions.json - do not hand-edit. */\n"
out += "const Borders = " + json.dumps({"edges": edges, "anomalies": anoms, "iso": P["iso"], "pos": P["pos"]}, ensure_ascii=False, separators=(",", ":")) + ";\n"
open(os.path.join(ROOT, "js/data/borders.js"), "w").write(out)
print("edges %d, anomalies %d, entities %d" % (len(edges), len(anoms), len(P["pos"])))
